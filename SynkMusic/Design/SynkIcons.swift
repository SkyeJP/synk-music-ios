// Heroicons 24x24 (outline stroke or solid fill) — same set the Android app
// bundles, so the visual language matches. Path strings are the raw SVG "d"
// attribute; a tiny parser converts them into CGPath, then SwiftUI strokes/fills.

struct SynkIcon: View {
    let vector: SynkVector
    var size: CGFloat = 24
    var tint: Color = Theme.fg
    var strokeWidth: CGFloat = 1.75

    var body: some View {
        let cgPath = vector.combinedCGPath()
        Canvas { ctx, canvasSize in
            let s = min(canvasSize.width, canvasSize.height) / 24
            var transform = CGAffineTransform(scaleX: s, y: s)
            guard let scaled = cgPath.copy(using: &transform) else { return }
            let path = Path(scaled)
            if vector.fill {
                ctx.fill(path, with: .color(tint))
            } else {
                ctx.stroke(
                    path,
                    with: .color(tint),
                    style: StrokeStyle(lineWidth: strokeWidth, lineCap: .round, lineJoin: .round)
                )
            }
        }
        .frame(width: size, height: size)
    }
}

struct SynkVector {
    let paths: [String]
    var fill: Bool = false

    func combinedCGPath() -> CGPath {
        let combined = CGMutablePath()
        for d in paths {
            combined.addPath(SVGPathParser.parse(d))
        }
        return combined
    }
}

